import torch
import numpy as np


# -----------------------------------------------------------
# Utility helpers
# -----------------------------------------------------------

def to_tensor(x, device=None, dtype=torch.float32):
    """
    Convert numpy array or Python list into a PyTorch tensor.
    If input is already a tensor, simply moves it to device/dtype.

    This ensures all downstream computations use consistent tensor types.
    """
    if isinstance(x, torch.Tensor):
        return x.to(device=device, dtype=dtype)
    return torch.tensor(x, device=device, dtype=dtype)


def flatten_batch_time(x):
    """
    Flatten a tensor of shape (N, T, d) → (N*T, d).

    Many metrics (MSE, R²) conceptually operate on a set of points,
    independent of trajectory grouping. Flattening ensures they treat
    all time steps equally.

    Accepts:
        - 2D tensor: (N, d) → unchanged
        - 3D tensor: (N, T, d) → reshape
    """
    if x.dim() == 2:
        return x
    elif x.dim() == 3:
        n, t, d = x.shape
        return x.reshape(n * t, d)
    else:
        raise ValueError("Input must be 2D or 3D tensor.")


# -----------------------------------------------------------
# Prediction metrics
# -----------------------------------------------------------

def one_step_mse(x_true, x_pred):
    """
    Compute 1-step Mean Squared Error (MSE).
    Used for short-term prediction accuracy.

    x_true, x_pred: (N, d) or (N, T, d)
    Returns: scalar MSE
    """
    x_true = to_tensor(x_true)
    x_pred = to_tensor(x_pred)
    diff = flatten_batch_time(x_true) - flatten_batch_time(x_pred)
    return torch.mean(torch.sum(diff * diff, dim=-1))


def multi_step_nrmse(x_true, x_pred, horizons, sigma_test=None):
    """
    Compute NRMSE(T) for multiple prediction horizons T.

    Normalized RMSE (NRMSE):
        RMSE(T) / sigma_test

    sigma_test: standard deviation of test data (optional).
                If not provided, computed automatically.

    x_true, x_pred: (N, T_max, d)
    horizons: list of integer prediction steps.
    Returns: dict {T: nrmse_value}
    """
    x_true = to_tensor(x_true)
    x_pred = to_tensor(x_pred)
    n, t_max, d = x_true.shape

    # Compute normalization constant
    if sigma_test is None:
        sigma_test = torch.std(x_true.reshape(n * t_max, d)) + 1e-8

    results = {}
    for T in horizons:
        if T >= t_max:
            continue
        # Error at time offset T
        err = x_true[:, T, :] - x_pred[:, T, :]
        mse_T = torch.mean(torch.sum(err * err, dim=-1))
        rmse_T = torch.sqrt(mse_T)
        results[T] = float((rmse_T / sigma_test).item())
    return results


def r2_score(x_true, x_pred):
    """
    Compute coefficient of determination (R²).
    Measures how much variance in the true data is explained by predictions.

        R² = 1 - SS_res / SS_tot

    where:
        SS_res = sum((y - y_pred)^2)
        SS_tot = sum((y - mean(y))^2)
    """
    x_true = flatten_batch_time(to_tensor(x_true))
    x_pred = flatten_batch_time(to_tensor(x_pred))
    mean_true = torch.mean(x_true, dim=0)

    ss_res = torch.sum((x_true - x_pred) ** 2)
    ss_tot = torch.sum((x_true - mean_true) ** 2) + 1e-8

    return float((1 - ss_res / ss_tot).item())


# -----------------------------------------------------------
# Phase-portrait fidelity
# -----------------------------------------------------------

def chamfer_distance_phase(x_true, x_pred, dims=(0, 1)):
    """
    Compute Chamfer distance between two phase-space trajectories.

    This measures geometric similarity of the trajectory shape—not just
    differences in time alignment. Often more meaningful than MSE for
    dynamical systems.

    Steps:
        1. Extract coordinates (e.g., x, x_dot)
        2. Compute pairwise distances: dist[i,j] = ||x_true[i] - x_pred[j]||
        3. Chamfer = average nearest-point distance (true→pred) +
                     average nearest-point distance (pred→true)

    Returns: scalar Chamfer distance
    """
    x_true = flatten_batch_time(to_tensor(x_true))[:, list(dims)]
    x_pred = flatten_batch_time(to_tensor(x_pred))[:, list(dims)]

    dist = torch.cdist(x_true, x_pred, p=2)

    d12 = torch.mean(torch.min(dist, dim=1).values)
    d21 = torch.mean(torch.min(dist, dim=0).values)

    return float((d12 + d21).item())


# -----------------------------------------------------------
# Koopman stability metrics
# -----------------------------------------------------------

def spectral_radius(K):
    """
    Compute spectral radius ρ(K) and full eigenvalue spectrum.

    Spectral radius:
        max(|λ_i|)

    A stable Koopman operator typically requires ρ(K) ≤ 1.
    """
    if isinstance(K, torch.Tensor):
        K = K.detach().cpu().numpy()

    eigvals = np.linalg.eigvals(K)
    rho = np.max(np.abs(eigvals))

    return float(rho), eigvals


def long_horizon_divergence_rate(x_true, x_pred):
    """
    Estimate long-horizon divergence rate by fitting:

        log(error_t) ≈ a * t + b

    This measures how prediction error grows with time steps.
    Larger slope → faster divergence → less stable dynamical model.

    Returns:
        slope (float): divergence rate
        errors (np array): raw per-timestep errors
    """
    x_true = to_tensor(x_true)
    x_pred = to_tensor(x_pred)

    n, T, d = x_true.shape

    # Mean trajectory error per time step
    errors = torch.sqrt(torch.sum((x_true - x_pred) ** 2, dim=-1)).mean(0)
    errors = errors + 1e-8  # avoid log(0)
    log_err = torch.log(errors)

    # Fit line: log(err_t) = a * t + b
    t = torch.arange(T, dtype=torch.float32)
    A = torch.stack([t, torch.ones_like(t)], dim=1)
    b = log_err.unsqueeze(1)

    # Modern PyTorch least-squares solver
    lstsq_result = torch.linalg.lstsq(A, b)

    slope = lstsq_result.solution[0, 0].item()

    return float(slope), errors.cpu().numpy()


# -----------------------------------------------------------
# Reconstruction error (for autoencoder-type models)
# -----------------------------------------------------------

def reconstruction_error(x_true, x_rec):
    """
    Compute reconstruction loss:
        || x - x_rec ||² averaged over all time steps.

    Used to measure how well the encoder/decoder pair preserves
    the original system state.

    x_true, x_rec: (N, T, d) or (N, d)
    """
    x_true = flatten_batch_time(to_tensor(x_true))
    x_rec = flatten_batch_time(to_tensor(x_rec))
    diff = x_true - x_rec
    return float(torch.mean(torch.sum(diff * diff, dim=-1)).item())