def to_tensor(x, device=None, dtype=torch.float32):
    if isinstance(x, torch.Tensor):
        return x.to(device=device, dtype=dtype)
    return torch.tensor(x, device=device, dtype=dtype)


# -----------------------------------------------------------
# Rollout (torch)
# -----------------------------------------------------------

@torch.no_grad()
def rollout(model, x0, steps):
    device = next(model.parameters()).device
    x = to_tensor(x0, device=device)
    preds = [x]

    for _ in range(steps):
        # 支持 model(x) 或 model.predict(x)
        if hasattr(model, "predict"):
            x = model.predict(x)
        else:
            x = model(x)

        preds.append(x)

    return torch.stack(preds, dim=0)


@torch.no_grad()
def rollout_batch(model, x0_batch, steps):
    device = next(model.parameters()).device
    x0_batch = to_tensor(x0_batch, device=device)

    trajs = []
    for i in range(x0_batch.shape[0]):
        trajs.append(rollout(model, x0_batch[i], steps))

    return torch.stack(trajs, dim=0)


# -----------------------------------------------------------
# Basic Error Metrics
# -----------------------------------------------------------

def mse_torch(y_true, y_pred):
    return torch.mean((y_true - y_pred) ** 2)

def rmse_torch(y_true, y_pred):
    return torch.sqrt(mse_torch(y_true, y_pred))

def nrmse_torch(y_true, y_pred, eps=1e-8):
    rmse = rmse_torch(y_true, y_pred)
    norm = torch.sqrt(torch.mean(y_true ** 2))
    return rmse / (norm + eps)

def r2_score_torch(y_true, y_pred, eps=1e-12):
    ss_res = torch.sum((y_true - y_pred) ** 2)
    ss_tot = torch.sum((y_true - torch.mean(y_true, dim=0)) ** 2)
    return 1 - ss_res / (ss_tot + eps)


# -----------------------------------------------------------
# Chamfer distance
# -----------------------------------------------------------

def chamfer_distance_torch(X, Y):
    dist = torch.cdist(X, Y, p=2) ** 2
    return torch.mean(torch.min(dist, dim=1).values) + \
           torch.mean(torch.min(dist, dim=0).values)


