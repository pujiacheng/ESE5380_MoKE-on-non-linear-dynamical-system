# This module implements all core evaluation metrics used in
# Koopman Autoencoder (KAE), EDMD, and MoKE-style models.
# It contains:
#   - Prediction accuracy metrics (MSE, NRMSE, R²)
#   - Phase-portrait fidelity metric (Chamfer distance)
#   - Stability metrics (spectral radius, divergence rate)
#   - Reconstruction error for autoencoder-based models
#
# All functions are implemented in a clean, model-agnostic style.
