# Prediction Evaluation
# -----------------------------------------------------------

@torch.no_grad()
def evaluate_prediction_metrics(model, x_test, y_test,
                                horizons=(1, 5, 10, 25, 50, 100),
                                compute_r2=True,
                                compute_phase_chamfer=True):

    device = next(model.parameters()).device
    x_test = to_tensor(x_test, device=device)
    y_test = to_tensor(y_test, device=device)

    N, T_plus_1, dim = y_test.shape
    max_h = max(horizons)

    y_pred = rollout_batch(model, x_test, steps=max_h)

    metrics = {}

    metrics["1-step MSE"] = mse_torch(y_test[:,1], y_pred[:,1]).item()

    for H in horizons:
        metrics[f"{H}-step NRMSE"] = nrmse_torch(
            y_test[:,H], y_pred[:,H]
        ).item()

    if compute_r2:
        yt = y_test[:,1:].reshape(-1, dim)
        yp = y_pred[:,1:].reshape(-1, dim)
        metrics["R2"] = r2_score_torch(yt, yp).item()

    if compute_phase_chamfer:
        X = y_test[:,1:].reshape(-1, dim)
        Y = y_pred[:,1:].reshape(-1, dim)
        metrics["phase_chamfer"] = chamfer_distance_torch(X, Y).item()

    return metrics


