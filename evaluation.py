def spectral_radius_torch(K):
    eigvals = torch.linalg.eigvals(K)
    return torch.max(torch.abs(eigvals)).real.item()

def divergence_rate_torch(y_true, y_pred, T=None, eps=1e-8):
    if T is None:
        T = y_true.shape[1] - 1

    err = y_true[:,T] - y_pred[:,T]
    norm = torch.norm(err, dim=-1).mean()
    return torch.log(norm + eps).item() / T


